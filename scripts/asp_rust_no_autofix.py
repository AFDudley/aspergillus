#!/usr/bin/env python3
"""Acceptance probe for asp-ce6.2 clause C9: the Rust checks report only.

Copies every committed ``rust/fixtures/<ASPnnn>/violating/`` crate into a
throwaway directory, runs the real Rust gate over the copy, and diffs the
copy's tracked-file bytes before and after — excluding ``target/`` and
``Cargo.lock``, cargo's own generated byproducts, not a rewrite of the
consumer's source. Emits one ``stdout_json`` object. Judges nothing
itself — the linked spec's ``then`` clauses own the verdict.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
RUST_MANIFEST = REPO_ROOT / "rust" / "Cargo.toml"
FIXTURES_DIR = REPO_ROOT / "rust" / "fixtures"

EXCLUDED_NAMES = {"target", "Cargo.lock"}


def gate_env() -> dict[str, str]:
    env = dict(os.environ)
    home = env.get("HOME", "")
    env["PATH"] = f"{home}/.cargo/bin:{home}/.bun/bin:{env.get('PATH', '')}"
    return env


def build_gate() -> Path:
    subprocess.run(
        ["cargo", "build", "--manifest-path", str(RUST_MANIFEST), "--offline", "-q"],
        check=True,
        env=gate_env(),
        cwd=REPO_ROOT,
    )
    return REPO_ROOT / "rust" / "target" / "debug" / "aspergillus-rust-gate"


def file_hashes(root: Path) -> dict[str, str]:
    hashes: dict[str, str] = {}
    for path in root.rglob("*"):
        if not path.is_file():
            continue
        if EXCLUDED_NAMES & set(path.relative_to(root).parts):
            continue
        hashes[str(path.relative_to(root))] = hashlib.sha256(path.read_bytes()).hexdigest()
    return hashes


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--json", action="store_true")
    parser.parse_args()

    gate = build_gate()

    with tempfile.TemporaryDirectory() as tmp:
        workspace = Path(tmp) / "workspace"
        workspace.mkdir()
        for violating_dir in sorted(FIXTURES_DIR.glob("*/violating")):
            rule_id = violating_dir.parent.name
            shutil.copytree(violating_dir, workspace / rule_id)

        before = file_hashes(workspace)
        result = subprocess.run(
            [str(gate), str(workspace)],
            capture_output=True,
            text=True,
            env=gate_env(),
            cwd=REPO_ROOT,
        )
        after = file_hashes(workspace)

        findings = sum(1 for line in result.stdout.splitlines() if line.strip())
        files_modified = sum(1 for key, digest in before.items() if after.get(key) != digest)
        files_modified += sum(1 for key in after if key not in before)

    observation = {"findings": findings, "files_modified": files_modified}
    print(json.dumps(observation))
    return 0


if __name__ == "__main__":
    sys.exit(main())
